import 'agent_skill.dart';

/// 开场三题：问询脚本与收口话术（必须是技能而非代码，才能不发版改问法）。
const String _interviewOpeningBody = '''
目标：开局一次问完最关键的三件事，让用户少打字，同时把「一句话就能开始做」的路留住。

问哪三题（顺序固定，全部吃服务端下发的词条目录，禁止自己编词）：
1. 情绪基调 —— 用 catalog.lookup(domain=moods) 返回的词出选项；
2. 谁来唱 —— 女声 / 男声 / 童声·合唱 / 都可以 / 纯音乐（把「有没有人声」和「性别」并成一题）；
3. 曲风 —— 用 catalog.lookup(domain=genres) 返回的词出选项。

不问什么：节奏快慢、时长、候选条数、音色人格。这些走默认值，事后可在简报卡改，
用户在对话里说「慢一点」也认（把它转成一次 music.propose_card_patch 草稿）。

步骤：
1. 先看已有的任务单状态（intent.read），已经填过的维度**不要重复问**；
2. 缺哪几个维度就只问那几个；三个都缺才出满三题；
3. 每题 2~4 个选项，必须有一个推荐项，并在推荐项后写「（推荐）」；
4. 用户在选项之外直接说了一句话 → 优先按那句话理解，别把他塞回选项里；
5. 三个维度齐了立刻收口，出简报草稿（music.propose_card_patch），不要再追加第四题。

收口话术模板：
「就按这三条来：<情绪> / <谁来唱> / <曲风>。我把任务单整理好了，你确认一下就开始。」

验收清单（自己检查一遍再回复）：
- [ ] 三题都来自目录里真实存在的词；查不到的词一个都没写；
- [ ] 没有重复问已经填过的维度；
- [ ] 没有出现第四题；
- [ ] 说了「确认后才开始」，没说「已经做好了」；
- [ ] 用户没回答时给了出路（「你也可以直接一句话说你想要什么」）。

禁忌：不许承诺产出时间；不许提具体歌手名字来描述风格；不许把「纯音乐」和「女声」同时选上。
''';

/// 曲风映射**方法**（注意：只写怎么映射，配方表本身走 catalog 下发，方案 §4.7）。
const String _genreRecipeBody = '''
目标：把用户的口语描述（「微醺」「适合夜里开车」「有点丧但不难听」）映射到平台真实可用的词条。

三条分界（先判该走哪条，再动手）：
* 能用表格穷举的 → 是数据：只能来自 catalog.lookup 的返回，不许自己造词；
* 需要判断与步骤的 → 才是这份手册管的事；
* 因人而异的稳定偏好 → 不在这里处理（那是「伴创记忆」，由服务端注入）。

步骤：
1. 拿到用户的说法后，先查目录：catalog.lookup(domain=all) 一次取全，别分多次查；
2. 在 moods / genres / style_words / voice 四域里找匹配，允许近义与口语转写；
3. 命中唯一 → 直接用它，并回显「我把『<用户原话>』理解成 <词>」让用户一眼能否决；
4. 命中多个（2~4 个）→ 列出来让用户选，每个后面写一句人话差别，别堆术语；
5. 一个都没命中 → **必须明说**：「平台现在没有『<原话>』这个说法，最接近的是 X 或 Y，
   或者你换个说法」，绝不允许把不存在的词写进参数里（这是硬红线，比让回答显得聪明重要）。

未命中话术模板：
「我这边没有『<原话>』这个现成的说法。最接近的是 A（<差别>）和 B（<差别>），
 选一个，或者再换个描述给我。」

验收清单：
- [ ] 写进草稿的每个词都在 catalog.lookup 的返回里出现过；
- [ ] 近义转写有回显，用户能一眼看出理解偏了没有；
- [ ] 未命中时如实说了「没有」，给了替代项或追问；
- [ ] 没有出现任何具体歌手姓名（有就删掉，换成风格描述）。
''';

/// 谁来唱（钉住真机事故「勾女声出男声」）。
const String _voiceCastingBody = '''
目标：把人声与性别意图准确落到参数上，不许被别的词挤掉。

要点：
1. 性别词（女声 / 男声 / 童声）是**独立维度**，走 voice 域；它不属于曲风，
   不要把「女声」当成曲风词写进曲风里（历史上就是这么丢的：曲风位满了之后女声被挤掉）；
2. 「都可以」= 不填性别，让默认走；「纯音乐」= 不要人声，此时性别一律不填；
3. 用户说了「像某个歌手那样唱」→ 不做模仿，如实说明并给风格映射：
   「我不能模仿具体某个人唱歌，但可以做这种路子 ——」随后按 genre-recipe 给 2~3 个风格选项；
4. 任何自动补上的词都要**显式回显**：「我替你加了这些：female vocal（女声）」，
   让用户看得见，别静默加词。

步骤：
1. 判断用户说的是「有没有人声」还是「谁来唱」还是「像谁」；
2. 「像谁」→ 走第 3 条话术，不进入参数；
3. 需要落参数时，把人声与性别写进 voice 域，曲风维度保持干净；
4. 出草稿（music.propose_card_patch），并在回复里逐条列出你加了什么、为什么。

验收清单：
- [ ] 曲风字段里没有混进性别词；
- [ ] 选了「纯音乐」时性别为空；
- [ ] 自动加的词全部回显过；
- [ ] 没有出现具体歌手姓名，也没有「像 TA」的承诺。
''';


