function ensureSeeds() {
  const now = U.nowIso();
  for (const s of SEEDS) {
    store.run(
      'INSERT OR IGNORE INTO agent_skills(name,description,body,rank,kind,enabled,delivered,updated_at) VALUES(?,?,?,?,?,?,?,?)',
      s.name, s.description, s.body, SERVER_RANK, s.kind || 'method', 1, 1, now);
  }
}

// 目录只给 name/description（正文按需 load_skill 取）：常驻成本只付目录，正文按回合付费取用。
function catalog() {
  return store.all(
    "SELECT name,description,rank,kind FROM agent_skills WHERE enabled=1 AND delivered=1 ORDER BY rank DESC,name ASC");
}

function load(name) {
  const r = store.get('SELECT name,description,body,rank,kind FROM agent_skills WHERE name=? AND enabled=1', String(name));
  return r || null;
}

// 用户勾选：只开/关**投递**，不改正文。未勾选的既不占目录也不占 token。
function setDelivered(name, on) {
  const r = store.run('UPDATE agent_skills SET delivered=?,updated_at=? WHERE name=?', on ? 1 : 0, U.nowIso(), String(name));
  return r && r.changes > 0;
}

module.exports = { ensureSeeds, catalog, load, setDelivered, SEEDS, SERVER_RANK };
